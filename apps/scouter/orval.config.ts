import { defineConfig } from 'orval';

const commentsPath = '/applicants/{applicantId}/documents/comments';

export default defineConfig({
  comments: {
    input: {
      // 명세 갱신과 코드 생성을 분리하기 위해 저장된 명세를 사용합니다.
      target: './schema.json',
      filters: { tags: ['서류 코멘트'] },
      override: {
        transformer: (schema) => {
          const comments = schema.paths?.[commentsPath];
          if (!comments?.get || !comments.post) {
            throw new Error('코멘트 조회·등록 API가 명세에 없습니다.');
          }

          // 서버 명세의 Location 헤더에 빠진 자료형만 보완합니다.
          const created = comments.post.responses?.['201'];
          if (created && !('$ref' in created)) {
            const location: unknown = created.headers?.Location;
            if (
              location &&
              typeof location === 'object' &&
              !('$ref' in location) &&
              !('schema' in location) &&
              !('content' in location)
            ) {
              created.headers = {
                ...created.headers,
                Location: { ...location, schema: { type: 'string' } },
              };
            }
          }

          // 첫 적용 범위를 코멘트 조회·등록으로 제한합니다.
          return {
            ...schema,
            paths: { [commentsPath]: { get: comments.get, post: comments.post } },
          };
        },
      },
    },
    output: {
      target: './src/apis/documents/generated/comments.gen.ts',
      client: 'react-query',
      httpClient: 'fetch',
      formatter: 'prettier',
      schemas: {
        path: './src/apis/documents/generated/comments.schema.gen.ts',
        type: 'zod',
        mode: 'single',
        importPath: '@/apis/documents/schema',
      },
      override: {
        header: () => ['Generated by Orval 8.41.0. Do not edit manually.'],
        // 생성된 요청도 기존 인증 클라이언트를 사용합니다.
        mutator: {
          path: './src/apis/generatedRequest.ts',
          name: 'generatedRequest',
          inferred: true,
        },
        fetch: { includeHttpResponseReturnType: false, runtimeValidation: true },
        includeZodSchemaInArguments: true,
        query: { version: 5 },
        operations: {
          readAllByApplicantId: {
            query: {
              useQuery: false,
              useSuspenseQuery: true,
              useMutation: false,
              shouldExportKeys: false,
              queryOptions: {
                path: './src/apis/documents/commentsQueryOptions.ts',
                name: 'commentQueryOptions',
                useHooks: false,
              },
            },
          },
          create_3: {
            query: { useQuery: false, useMutation: true },
            // 코멘트 등록의 JSON 본문 검사만 생성합니다.
            transformer: (operation) => {
              const { body } = operation;
              return {
                ...operation,
                body: {
                  ...body,
                  implementation: `${body.definition}.parse(${body.implementation})`,
                  imports: body.imports.map((schema) => ({ ...schema, values: true })),
                },
              };
            },
          },
        },
        zod: { version: 4, generateReusableSchemas: true },
      },
    },
  },
});
